"""
P54 - Safe Schema Modernization (IMPLEMENTATION phase, generate-only).

Reads: AGENTS.md, memory/*, schema findings from P53, live schema inventory.
Writes (deterministic, evidence-backed, NO execution):
  output/migrations/p54_go_migration.sql        # changes that pass ALL 6 gates
  output/migrations/p54_blocked_reference.sql   # SQL/approach for BLOCKED items (do NOT run)
  output/reports/p54_migration_preview.sql      # human-readable preview = go_migration.sql
  output/reports/p54_schema_plan.md
  output/reports/p54_blocked_changes.md

This script NEVER opens production.db and NEVER runs any SQL.
It only writes migration files from embedded, evidence-backed SQL constants.

Gates (from task): a change is GO only if it satisfies ALL of
  1 no production risk   2 no Flutter breakage   3 no FastAPI breakage
  4 no Drift breakage     5 fully reversible      6 covered by migration SQL
Otherwise -> BLOCKED.

Evidence basis (queries run during analysis against output/import/production.db):
  SELECT COUNT(*), COUNT(DISTINCT whisky_id), SUM(whisky_id IS NULL)
    FROM whiskies;            -- 3293, 3293, 0  (whisky_id is a clean TEXT key)
  PRAGMA foreign_key_check;   -- 'foreign key mismatch - price_history referencing whiskies'
  SELECT COUNT(*) FROM whiskies WHERE typeof(abv)='text';  -- 1314 (all end with '%')
  SELECT COUNT(*) FROM whiskies WHERE typeof(abv)='real';   -- 18
  SELECT COUNT(*) FROM whiskies WHERE abv<0 OR abv>100;     -- 1314 (textual, post-fix -> 0)
  -- distilleries REAL-typed text cols (owner, founded_year, ...): ALL NULL (0 non-null)
  -- tasting_notes REAL-typed cols: source_url=109, source_name=77, notes_for_review=1461 TEXT (non-null)
  -- link tables (bottler_product_links, distillery_company_links, whisky_product_entities): 0 rows
  -- Drift DB (frontend) is a SEPARATE schema (malt_radar_v2, v6); does not read production.db tables.
  -- FastAPI reads whiskies/distilleries/tasting_notes/flavor_profiles/price_history by TEXT keys.
"""

