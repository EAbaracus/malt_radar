# ---------------------------------------------------------------------------
# GO migration: only changes that pass ALL 6 gates.
# Bundle into ONE transaction for atomicity + rollback safety.
# ---------------------------------------------------------------------------
GO_MIGRATION = """-- ============================================================================
-- P54 GO MIGRATION  (generated by scripts/p54_schema_modernization.py)
-- DO NOT EXECUTE AUTOMATICALLY. Apply on a verified staging copy of production.db,
-- inside the transaction below, then assert the post-conditions.
--
-- Scope (GO items only):
--   G-A: ABV type normalization (verified in P53)        -> UPDATE, reversible
--   G-B: Missing indexes on hot join/lookup columns      -> CREATE INDEX, reversible
--
-- NOT included (see p54_blocked_changes.md):
--   whisky_id PRIMARY KEY (requires full table rebuild -> BLOCKED, own gated migration)
--   distilleries/tasting_notes column-type rebuilds     -> BLOCKED (latent, no prod risk now)
--   link-table id-type mismatch                          -> BLOCKED (needs id-strategy decision)
--   price_history removal                                -> BLOCKED (P53: live data + live code)
-- ============================================================================

-- 0) Guard: ensure we are on the populated, expected DB shape.
PRAGMA foreign_keys = OFF;   -- table has no enforced FKs we mutate here

-- 1) PRE-CONDITIONS (assert before applying)
PRAGMA integrity_check;                                       -- expected: ok
SELECT COUNT(*) FROM whiskies WHERE typeof(abv)='text';      -- expected: 1314
SELECT COUNT(*) FROM whiskies WHERE abv<0 OR abv>100;        -- expected: 1314
SELECT COUNT(*) FROM whiskies WHERE typeof(abv)='real';      -- expected: 18

-- 2) APPLY (single transaction)
BEGIN IMMEDIATE;

  -- G-A: normalize ABV text+% -> REAL percentage.
  -- Correct transform is STRIP('%') + CAST (NOT divide by 100).
  -- WHERE isolates only the 1314 bad rows; the 18 valid REAL rows and 1961 NULLs untouched.
  UPDATE whiskies
     SET abv = CAST(REPLACE(REPLACE(abv, ',', '.'), '%', '') AS REAL)
   WHERE typeof(abv) = 'text'
     AND abv LIKE '%';

  -- G-B: indexes on hot columns. Safe, query-plan only, no semantic change.
  CREATE INDEX IF NOT EXISTS idx_whiskies_distillery_id ON whiskies(distillery_id);
  CREATE INDEX IF NOT EXISTS idx_whiskies_name          ON whiskies(name);
  CREATE INDEX IF NOT EXISTS idx_whiskies_country       ON whiskies(country);
  CREATE INDEX IF NOT EXISTS idx_tasting_notes_whisky_id ON tasting_notes(whisky_id);
  CREATE INDEX IF NOT EXISTS idx_flavor_profiles_whisky_id ON flavor_profiles(whisky_id);
  CREATE INDEX IF NOT EXISTS idx_price_history_whisky_id ON price_history(whisky_id);

COMMIT;

-- 3) POST-CONDITIONS (assert before declaring success; else ROLLBACK)
PRAGMA integrity_check;                                       -- expected: ok
SELECT COUNT(*) FROM whiskies WHERE typeof(abv)='text';      -- expected: 0
SELECT COUNT(*) FROM whiskies WHERE abv<0 OR abv>100;        -- expected: 0
SELECT COUNT(*), MIN(abv), MAX(abv)
  FROM whiskies WHERE abv IS NOT NULL;                       -- expected: 1332, 39.9, 71.35
SELECT COUNT(*) FROM sqlite_master
  WHERE type='index' AND name IN
   ('idx_whiskies_distillery_id','idx_whiskies_name','idx_whiskies_country',
    'idx_tasting_notes_whisky_id','idx_flavor_profiles_whisky_id','idx_price_history_whisky_id');
                                                              -- expected: 6

-- 4) REVERSIBILITY: every change is undoable
--    ABV: re-import from source CSV OR restore from the pre-migration backup copy
--         (Rule 02: output/import/backups/production_p54_pre<ts>.db). The UPDATE is also
--         contained in the same transaction, so an error triggers ROLLBACK with zero change.
--    Indexes: DROP INDEX IF EXISTS idx_whiskies_distillery_id; ... (all 6) restores exactly.
"""

